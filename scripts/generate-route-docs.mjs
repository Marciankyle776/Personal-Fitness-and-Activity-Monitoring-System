// Builds docs/API-ROUTES.md from the server's route files so the API reference cannot drift from the code.
//   node scripts/generate-route-docs.mjs          write the file
//   node scripts/generate-route-docs.mjs --check  exit 1 if the file is out of date (use in CI)
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";

const root = new URL("../server/", import.meta.url);
const read = (p) => readFileSync(new URL(p, root), "utf8");

// 1. Which route file is mounted at which path (app.js)
const app = read("app.js");
const imports = Object.fromEntries([...app.matchAll(/import (\w+) from "\.\/routes\/([\w.]+)\.js"/g)].map((m) => [m[1], m[2]]));
const mounts = [...app.matchAll(/app\.use\("(\/api\/[\w-]+)", (\w+)\)/g)].map((m) => ({ base: m[1], file: imports[m[2]] })).filter((m) => m.file);

// 2. Standard CRUD routes added by crudRouter(), and the routes each file declares itself
const CRUD = [["GET", ""], ["POST", ""], ["GET", "/:id"], ["PUT", "/:id"], ["DELETE", "/:id"]];
const rows = [];
for (const { base, file } of mounts) {
  const src = read(`routes/${file}.js`);
  const isCrud = src.includes("crudRouter(");
  const own = [...src.matchAll(/router\.(get|post|put|delete)\(\s*"([^"]*)"((?:[^;]|\n)*?)\);/g)].map((m) => ({ method: m[1].toUpperCase(), path: m[2], rest: m[3] }));
  const guarded = src.includes("router.use(protect") || isCrud;
  const all = [...(isCrud ? CRUD.map(([method, path]) => ({ method, path, rest: "" })) : []), ...own];
  for (const r of all) {
    const notes = [];
    const limiter = r.rest.match(/(\w+Limiter)/g);
    if (limiter) notes.push(...limiter);
    const crudRoute = isCrud && !own.includes(r);
    if (/validate\(/.test(r.rest) || /router\.use\(protect, validate\(/.test(src) || (crudRoute && ["GET", "POST", "PUT"].includes(r.method) && r.path !== "/:id")) notes.push("validated");
    const isPublic = base === "/api/auth" && !/protect/.test(r.rest) && !["/logout"].includes(r.path) ? true : !guarded && !/protect/.test(r.rest);
    rows.push({ method: r.method, url: `${base}${r.path === "/" ? "" : r.path}`, auth: isPublic ? "public" : "signed in", notes: [...new Set(notes)].join(", ") });
  }
}
rows.unshift({ method: "GET", url: "/api/health", auth: "public", notes: "readiness (503 when the database is down)" });
const order = { GET: 0, POST: 1, PUT: 2, DELETE: 3 };

const body = [
  "# API route reference",
  "",
  "> Generated by `node scripts/generate-route-docs.mjs` from `server/app.js` and `server/routes/*.js`.",
  "> Do not edit by hand. Run `npm run docs:routes` after changing routes, and `npm run docs:check` in CI.",
  "",
  "| Method | Path | Access | Notes |",
  "|---|---|---|---|",
  ...rows.map((r) => `| ${r.method} | \`${r.url}\` | ${r.auth} | ${r.notes} |`),
  "",
  `Total: ${rows.length} routes.`,
  "",
].join("\n");

const out = new URL("../docs/API-ROUTES.md", import.meta.url);
if (process.argv.includes("--check")) {
  const current = existsSync(out) ? readFileSync(out, "utf8") : "";
  if (current !== body) { console.error("docs/API-ROUTES.md is out of date. Run: npm run docs:routes"); process.exit(1); }
  console.log(`docs/API-ROUTES.md is up to date (${rows.length} routes).`);
} else {
  writeFileSync(out, body);
  console.log(`Wrote docs/API-ROUTES.md (${rows.length} routes).`);
}
